import assert from 'node:assert/strict';
import {normalizeRack,parseDictionary,isPalindrome,fitsRack,leftoverLetters,tileScore,scoreWord,solveRack} from './words-core.js';
const rack='X O Y E N T N U I D T E';
assert.equal(normalizeRack(rack),'XOYENTNUIDTE');
assert.equal(isPalindrome('TENET'),true);
assert.equal(isPalindrome('DETENTION'),false);
assert.equal(fitsRack('DETENTION',rack),true);
assert.equal(fitsRack('TENET',rack),true);
assert.equal(fitsRack('DENTITION',rack),false);
assert.equal(fitsRack('NONENTITY',rack),false);
assert.equal(fitsRack('TOY',rack),true);
assert.equal(fitsRack('TOY',rack,true),false);
assert.equal(fitsRack('CAT','C?T'),true);
assert.equal(fitsRack('CATS','C?T'),false);
assert.equal(fitsRack('CAT','C?T',true),true);
assert.equal(tileScore('CAT','C?T'),4);
assert.equal(leftoverLetters('TENET',rack),'DINOUXY');
assert.equal(scoreWord('TENET',rack,{mode:'length',bonus:2}).score,10);
assert.equal(scoreWord('TENET',rack,{mode:'tiles',bonus:3}).score,15);
assert.deepEqual(parseDictionary('tenet\nTENET\nbad-word\nDETENTION\n'), ['TENET','DETENTION']);
const results=solveRack(['DETENTION','TENET','DENTITION','TOY'],rack,{mode:'length',bonus:2});
assert.equal(results[0].word,'TENET');
assert.equal(results.find(x=>x.word==='DETENTION').score,9);
assert.equal(solveRack(['TENET','TOY'],rack,{exact:true}).length,0);
assert.deepEqual(solveRack(['TOY','TENET'],rack,{palindromeOnly:true}).map(x=>x.word),['TENET']);
console.log('PASS word solver rack, palindrome, wildcard, duplicate, scoring and filtering tests');
